/**
 * Generates `packages/platform/src/vorbisSetupHeaders.ts` from
 * `libraries/FFGAppImport/AssetImport/OggVorbisHeader.cs`.
 *
 * FSB5 stores Vorbis packets with their three headers stripped. The setup
 * header cannot be reconstructed, so Valkyrie carries three known ones keyed
 * by CRC32 — 590 lines of data. Generating rather than retyping keeps them
 * identical to the source and makes a drift obvious.
 *
 *   node tools/ffg/generate-vorbis-headers.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = join(here, '../../..')
const source = readFileSync(
  join(repo, 'libraries/FFGAppImport/AssetImport/OggVorbisHeader.cs'),
  'utf8',
)

const NAMES = ['setup_header_1_4800', 'setup_header_1_4800_alt', 'setup_header_2_4800']

/** The `if (crc == N) return name;` mapping, read from the source. */
const mapping = [...source.matchAll(/if \(crc == (\d+)\)\s*\{\s*return (\w+);/g)].map((m) => [
  Number(m[1]),
  m[2],
])
if (mapping.length !== NAMES.length) {
  throw new Error(`Expected ${NAMES.length} CRC mappings, found ${mapping.length}`)
}

const blobs = new Map()
for (const name of NAMES) {
  const match = new RegExp(`${name} = new byte\\[\\] \\{([^}]*)\\}`, 's').exec(source)
  if (match === null) throw new Error(`${name} not found in OggVorbisHeader.cs`)
  const values = match[1]
    .split(/[,\s]+/)
    .filter((v) => v.length > 0)
    .map(Number)
  if (values.some((v) => !Number.isInteger(v) || v < 0 || v > 255)) {
    throw new Error(`${name} holds a value outside a byte`)
  }
  blobs.set(name, values)
}

const lines = []
lines.push(`/**`)
lines.push(` * Vorbis setup headers, generated by tools/ffg/generate-vorbis-headers.mjs`)
lines.push(` * from libraries/FFGAppImport/AssetImport/OggVorbisHeader.cs — do not edit.`)
lines.push(` *`)
lines.push(` * FSB5 strips the three Vorbis headers from every packet stream. The`)
lines.push(` * identification and comment headers can be rebuilt, but the setup header`)
lines.push(` * cannot, so the known ones are carried here and looked up by the CRC32 the`)
lines.push(` * FSB records. The C# comments note it supports only these.`)
lines.push(` */`)
lines.push('')
for (const [name, values] of blobs) {
  lines.push(`/** ${values.length} bytes. */`)
  lines.push(`const ${toCamel(name)} = Uint8Array.from([`)
  for (let i = 0; i < values.length; i += 24) {
    lines.push(`  ${values.slice(i, i + 24).join(', ')},`)
  }
  lines.push('])')
  lines.push('')
}

lines.push('/** CRC32 of the stream, as recorded in the FSB, to its setup header. */')
lines.push('const BY_CRC = new Map<number, Uint8Array>([')
for (const [crc, name] of mapping) {
  lines.push(`  [${crc}, ${toCamel(name)}],`)
}
lines.push('])')
lines.push('')
lines.push('/** The setup header for a stream, or null when it is not one of the known ones. */')
lines.push('export function vorbisSetupHeader(crc32: number): Uint8Array | null {')
lines.push('  return BY_CRC.get(crc32 >>> 0) ?? null')
lines.push('}')
lines.push('')

writeFileSync(join(here, '../../packages/platform/src/vorbisSetupHeaders.ts'), lines.join('\n'))
console.log(
  `generated ${blobs.size} setup headers (${[...blobs.values()].map((v) => v.length).join(', ')} bytes)`,
)

function toCamel(name) {
  return name.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase())
}
